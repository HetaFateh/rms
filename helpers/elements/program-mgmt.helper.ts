/**
 * helpers/elements/program-mgmt.helper.ts
 * ──────────────────────────────────────────────────────────────────────────────
 * Locators AND high-level action helpers for the Program Management feature.
 *
 * Structure:
 *   1. Element factories  – return raw Locator objects, NO side-effects.
 *   2. Action helpers     – `async` functions that accept `page` (and optionally
 *      data) and perform a meaningful business step (e.g. fillTabProgram).
 *
 * Rules (see agents.md):
 *   ✅ Element factories MUST NOT contain `await` or interaction calls.
 *   ✅ Action helpers import element factories and orchestrate clicks/fills.
 *   ✅ All names are camelCase, prefixed by their role:
 *       btn*, input*, dropdown*, checkbox*, tab*, textarea*, upload*
 * ──────────────────────────────────────────────────────────────────────────────
 */

