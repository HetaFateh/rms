/**
 * Update program date range using the date picker component.
 * Follows temp_codegen.txt logic:
 * - First date: day before current day (e.g., if today is May 20th, choose May 19th)
 * - Last date: first date + 12 days (e.g., if first date is May 19th, choose May 31st)
 */
export async function updateProgramDateRange(page: Page): Promise<void> {
  // Calculate dates based on current date
  const today = new Date();
  const startDate = new Date(today);
  startDate.setDate(today.getDate() - 1); // Day before current day
  
  const endDate = new Date(startDate);
  endDate.setDate(startDate.getDate() + 12); // First date + 12 days
  
  // Format dates for the date picker
  const startDay = startDate.getDate();
  const startMonth = startDate.toLocaleString('en-US', { month: 'long' });
  const startYear = startDate.getFullYear();
  
  const endDay = endDate.getDate();
  const endMonth = endDate.toLocaleString('en-US', { month: 'long' });
  const endYear = endDate.getFullYear();
  
  // Format day with ordinal suffix (e.g., "19th", "1st", "22nd")
  const getOrdinalSuffix = (day: number): string => {
    if (day > 3 && day < 21) return 'th';
    switch (day % 10) {
      case 1: return 'st';
      case 2: return 'nd';
      case 3: return 'rd';
      default: return 'th';
    }
  };
  
  const startDayWithSuffix = `${startDay}${getOrdinalSuffix(startDay)}`;
  const endDayWithSuffix = `${endDay}${getOrdinalSuffix(endDay)}`;
  
  // Get day of week names
  const startDayOfWeek = startDate.toLocaleString('en-US', { weekday: 'long' });
  const endDayOfWeek = endDate.toLocaleString('en-US', { weekday: 'long' });
  
  // Click the date range picker to open it
  await page.getByRole('textbox', { name: 'Select date range' }).click();
  
  // Wait for calendar to appear
  await page.waitForTimeout(500);
  
  // Click the start date
  // Format: "Choose Tuesday, May 19th, 2026"
  const startDateLabel = `Choose ${startDayOfWeek}, ${startMonth} ${startDayWithSuffix}, ${startYear}`;
  await page.getByRole('gridcell', { name: startDateLabel }).click();
  
  // Click the end date
  // Format: "Choose Sunday, May 31st, 2026"
  const endDateLabel = `Choose ${endDayOfWeek}, ${endMonth} ${endDayWithSuffix}, ${endYear}`;
  await page.getByRole('gridcell', { name: endDateLabel }).click();
  
  // Wait for date picker to close
  await page.waitForTimeout(500);
}

