/**
 * Navigate from the dashboard to the Create Program form.
 */
export async function navigateToCreateProgram(page: Page): Promise<void> {
  const nav = programMgmtNavElements(page);
  await nav.btnManageProgram.click();
  await nav.linkProgramManagement.click();
  await nav.linkTambahProgram.click();
}

/**
 * Fill the main "Program" tab and save it.
 * @param imagePath Absolute path to the KV image file.
 */
export async function fillTabProgram(page: Page, imagePath: string): Promise<void> {
  const el = tabProgramElements(page);

  await el.inputNama.fill(form_daftar_program.name);
  await el.inputKode.fill(form_daftar_program.code);
  await el.inputThresholdExpired.fill(form_daftar_program.thresholdExpired);
  await el.textareaInfo.fill(form_daftar_program.name);

  // React-Select dropdowns
  // ⚠️ These rely on brittle CSS selectors — tag for data-testid once available.
  await el.dropdownKategori.click();
  await el.optionKvKategoriProgram.click();
  await el.dropdownSubKategori.click();
  await el.optionKhususKv.click();
  await el.dropdownSubKategori.click();
  await el.optionKvProduk.click();
  await el.dropdownProduk.click();
  await el.optionHaloUnlimited.click();

  // Date-range spinbuttons
  await el.spinbuttonTanggalMulai.fill('2');
  await el.spinbuttonBulanMulai.fill('2');
  await el.spinbuttonTanggalAkhir.fill('1');
  await el.spinbuttonBulanAkhir.fill('5');

  await el.btnSimpan.click();

  await el.textareaKvWording.fill(form_daftar_program.name);
  await el.uploadProgramImage.setInputFiles(imagePath);
  await el.inputRedirectLink.fill(form_daftar_program.redirectLink);
  await el.inputMaxPoin.fill(form_daftar_program.maxPoin);
  await el.inputBudget.fill(form_daftar_program.budget);
  await el.inputThresholdBudget.fill(form_daftar_program.thresholdBudget);

  await el.dropdownChannel.click();
  await el.optionKvChannel.click();

  await el.textareaNotifSms.fill(form_daftar_program.name);
  await el.checkboxTelkomsel.check();
  await el.checkboxNonTelkomsel.check();
}

/**
 * Switch to the Foto tab and upload a photo with its title and description.
 * @param imagePath Absolute path to the image file.
 */
export async function fillTabFoto(page: Page, imagePath: string): Promise<void> {
  const el = tabFotoElements(page);

  await el.tabFoto.click();
  await el.uploadFoto.setInputFiles(imagePath);
  await el.inputFotoJudul.fill(form_daftar_program.name);
  await el.textareaFotoDeskripsi.fill(form_daftar_program.name);
  await el.inputWording.fill(form_daftar_program.wording);
  await el.btnTambahWording.click();
}

/**
 * Switch to the Payment Limitation tab and add one payment method row.
 */
export async function fillTabPaymentLimitation(page: Page): Promise<void> {
  const el = tabPaymentLimitationElements(page);

  await el.tabPaymentLimitation.click();
  await el.btnTambah.click();
  await el.comboboxPayment.selectOption('53');
  await el.btnKonfirmasiRow.click();
  await el.inputTermAndCondition.fill(' Test Automation');
  await el.btnSimpan.click();
}

/**
 * Switch to the Sales Fee tab, set a period, fill agent fees, and save.
 */
export async function fillTabSalesFee(page: Page): Promise<void> {
  const el = tabSalesFeeElements(page);

  await el.tabSalesFee.click();
  await el.comboboxPeriod.selectOption('1');
  await el.inputAgentUpline.fill(form_daftar_program.agentUpline);
  await el.inputAgentDownline1.fill(form_daftar_program.agentDownline1);
  await el.btnSimpan.click();
}
