/**
 * Select a Customer Bonus option from the dropdown and fill Earning Poin fields in the modal.
 * This opens a modal dialog where we need to fill the Earning Poin fields.
 * @param bonusName The name of the bonus option to select.
 * @param earningPoinValue The value to fill in all 4 Earning Poin fields (e.g., '1').
 */
export async function selectCustomerBonusAndFillEarningPoin(
  page: Page,
  bonusName: string,
  earningPoinValue: string
): Promise<void> {
  // Use the exact locator from temp_codegen.txt
  await page.locator('.mb-3 > .css-b62m3t-container > .css-13cymwt-control > .css-hlgwow > .css-19bb58m').click();
  // Wait for dropdown options to appear
  await page.waitForTimeout(500);
  await page.getByRole('option', { name: bonusName }).click();
  
  // Wait for the modal dialog to appear
  const modal = page.getByRole('dialog', { name: 'Produk' });
  await modal.waitFor({ state: 'visible', timeout: 5000 });
  
  // Fill all 4 Earning Poin fields in the modal
  // The spinbuttons appear in order within the modal: Earning Poin 1, 2, 3, 4
  // We scope to the modal and get spinbuttons by index
  const spinbuttons = modal.getByRole('spinbutton');
  
  // Fill each field (indices 0-3 for Earning Poin 1-4)
  await spinbuttons.nth(0).fill(earningPoinValue); // Earning Poin 1
  await spinbuttons.nth(1).fill(earningPoinValue); // Earning Poin 2
  await spinbuttons.nth(2).fill(earningPoinValue); // Earning Poin 3
  await spinbuttons.nth(3).fill(earningPoinValue); // Earning Poin 4
  
  // Click the Simpan button in the modal to save
  await modal.getByRole('button', { name: 'Simpan' }).click();
  
  // Wait for modal to close
  await modal.waitFor({ state: 'hidden', timeout: 5000 });
}

